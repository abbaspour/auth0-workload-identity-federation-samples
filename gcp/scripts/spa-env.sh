#!/usr/bin/env bash

set -ueo pipefail

DIR="${BASH_SOURCE[0]%/*}"
[ "$DIR" = "${BASH_SOURCE[0]}" ] && DIR="."
readonly DIR

. "${DIR}/lib.sh"

function usage() {
    cat <<END >&2
USAGE: $0 [-o env_file] [-h]
        -o file        # output file (default: ${DIR}/../spa/.env.local)
        -h|?           # usage

Writes the SPA's Vite configuration from the Terraform outputs in gcp/tf.

eg,
     $0
END
    exit $1
}

declare OUT="${DIR}/../spa/.env.local"

while getopts ":o:h?" opt; do
    case ${opt} in
    o) OUT=${OPTARG} ;;
    h | ?) usage 0 ;;
    \?) [[ "${OPTARG}" == "?" ]] && usage 0
        echo >&2 "ERROR: illegal option -- ${OPTARG}"
        usage 1 ;;
    :) echo >&2 "ERROR: option requires an argument -- ${OPTARG}"; usage 1 ;;
    esac
done

declare -a names=(VITE_AUTH0_DOMAIN VITE_AUTH0_CLIENT_ID VITE_AUTH0_AUDIENCE VITE_GCP_WIP_AUDIENCE VITE_GCS_BUCKET)
declare -a outputs=(auth0_issuer_domain spa_client_id api_audience workload_identity_provider bucket_name)
declare -a lines=("# Generated by gcp/scripts/spa-env.sh from terraform output. Not committed.")

for i in "${!names[@]}"; do
    value=$(tf_output "${outputs[${i}]}")
    [[ -n "${value}" ]] || { echo >&2 "ERROR: terraform output ${outputs[${i}]} is empty (is gcp/tf applied?)"; usage 1; }
    lines+=("${names[${i}]}=${value}")
done

printf '%s\n' "${lines[@]}" > "${OUT}"

echo >&2 "Wrote ${OUT}"
